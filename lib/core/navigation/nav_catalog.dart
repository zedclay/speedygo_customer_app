  static List<NavEntry> get screens => all
      .where((e) => e.surface != NavSurface.token && e.route.isNotEmpty)
      .toList();

  static NavEntry? byId(String id) {
    for (final entry in all) {
      if (entry.id == id) {
        return entry;
      }
    }
    return null;
  }

  static NavEntry? byRoute(String route) {
    for (final entry in screens) {
      if (entry.route == route) {
        return entry;
      }
    }
    return null;
  }

  static Map<String, List<NavEntry>> grouped() {
    final map = <String, List<NavEntry>>{};
    for (final entry in screens) {
      map.putIfAbsent(entry.group, () => []).add(entry);
    }
    return map;
  }
